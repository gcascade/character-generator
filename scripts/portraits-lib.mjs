// Shared helpers of the portrait scripts (spec 009, spec 011): enums, paths, manifest and guide.
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

export const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const types = readFileSync(join(root, 'src/types/character.ts'), 'utf8');

/** Values of an `as const` enum object of src/types/character.ts. */
const values = (name) => {
  const body = types.match(
    new RegExp(`export const ${name} = \\{([^}]*)\\}`),
  )[1];
  return [...body.matchAll(/:\s*'([^']+)'/g)].map((m) => m[1]);
};

export const slug = (value) =>
  value
    .toLowerCase()
    .replace(/[^a-z]+/g, '-')
    .replace(/^-|-$/g, '');

export const RACES = values('CharacterRaces');
export const CLASSES = values('CharacterClasses');
/** Non-binary characters use one of both. */
export const VARIANTS = ['male', 'female'];
export const EXTENSIONS = ['png', 'webp', 'jpg'];

const IMAGES = join(root, 'public/images');
const MANIFEST = join(root, 'src/data/content/portraitFiles.json');
const GUIDE = join(root, 'docs/portraits.md');

/** Path of a portrait without extension, relative to public/images. */
export const portraitStem = (race, characterClass, variant) =>
  `${slug(race)}/${slug(characterClass)}/${variant}1`;

/** The existing file of a portrait (relative to public/images), if any. */
export const existingPortrait = (stem) =>
  EXTENSIONS.map((ext) => `${stem}.${ext}`).find((file) =>
    existsSync(join(IMAGES, file)),
  );

export const allPortraits = () =>
  RACES.flatMap((race) =>
    CLASSES.flatMap((characterClass) =>
      VARIANTS.map((variant) => ({
        race,
        characterClass,
        variant,
        stem: portraitStem(race, characterClass, variant),
      })),
    ),
  );

/** Every portrait file under public/images/<race>/<class>/, sorted (read by the app). */
export const writeManifest = () => {
  const files = [];
  for (const race of readdirSync(IMAGES, { withFileTypes: true })) {
    if (!race.isDirectory()) continue;
    for (const cls of readdirSync(join(IMAGES, race.name), {
      withFileTypes: true,
    })) {
      if (!cls.isDirectory()) continue;
      for (const file of readdirSync(join(IMAGES, race.name, cls.name))) {
        if (/^(male|female)1\.(png|webp|jpg)$/.test(file)) {
          files.push(`${race.name}/${cls.name}/${file}`);
        }
      }
    }
  }
  files.sort();
  writeFileSync(MANIFEST, `${JSON.stringify(files, null, 2)}\n`);
  return files;
};

/** docs/portraits.md: how to add portraits, and which ones are missing. */
export const writeGuide = () => {
  const portraits = allPortraits();
  const missing = portraits.filter((p) => !existingPortrait(p.stem));
  const rows = RACES.flatMap((race) =>
    CLASSES.map((characterClass) => {
      const cells = VARIANTS.map((variant) => {
        const stem = portraitStem(race, characterClass, variant);
        return existingPortrait(stem) ? '✅' : `❌ \`${stem}\``;
      });
      return `| ${race} | ${characterClass} | ${cells.join(' | ')} |`;
    }),
  );
  const doc = `# Portraits

Generated by \`npm run portraits\` (and by \`npm run portraits:paint\`): run it again after adding images.

**${portraits.length - missing.length} of ${portraits.length} portraits exist; ${missing.length} are missing.** Until a
portrait exists, the app shows the race emblem (a shield in the class colour with the race symbol), so nothing is
broken. The app reads the list of existing files from \`src/data/content/portraitFiles.json\`, written by both scripts.

## Painting the missing portraits with AI (spec 011)

\`npm run portraits:paint\` runs on your own computer, paints the missing portraits one by one and writes them at the
right place. It never overwrites an existing portrait, and a new run continues where the last one stopped.

\`\`\`bash
npm run portraits:paint -- --dry-run          # lists what would be painted, with the prompts; no network
npm run portraits:paint -- --limit 2          # paints 2 portraits with AI Horde, without any account
npm run portraits:paint                       # paints everything missing (can take hours without an account)
npm run portraits:paint -- --only gnome/bard/female1
npm run portraits:paint -- --model any        # AI Horde: any free model, much shorter queue, style varies more
npm run portraits:paint -- --timeout 120      # wait up to 2 hours per portrait in the queue (default 60 min)
\`\`\`

AI Horde paints at 768 × 768 with one painterly model by default (\`--size\` and \`--model\` change it). Few volunteers
serve that model, so a new account can wait around 20 minutes per portrait: \`--model any\` is much faster but the
style varies more, and Cloudflare (below) takes a few seconds per portrait.

**Rejecting portraits**: \`npm run portraits:remove -- orc/bard/female dark-elf/mage/male\` deletes them and updates
the list; the next \`npm run portraits:paint\` paints them again (add \`--dry-run\` to check first).

Cloudflare's FLUX model often paints fake artist signatures in the corners: trim them away and shrink the new
images (768 × 768 WebP, ~50 KB instead of ~650 KB) with \`python scripts/trim-portraits.py\` (needs Python 3 and
\`pip install pillow\`). Then look at the new images in \`public/images\`, delete the ones you don't like (run \`npm run portraits\` to update
the list), and commit \`public/images\`, \`src/data/content/portraitFiles.json\` and this file.

### Services

- **AI Horde, no account** (default): free community queue run by volunteers; anonymous requests come last, so expect
  one to several minutes per portrait. Nothing to set up.
- **AI Horde with a free account** (higher priority): register at <https://aihorde.net/register> (a user name is
  enough), copy the API key it shows (keep it: it is shown once) into \`AI_HORDE_API_KEY\` in your \`.env\` file (see
  below), then run \`npm run portraits:paint\`.
- **Cloudflare Workers AI** (fast, FLUX model, free daily quota): create a free account at
  <https://dash.cloudflare.com/sign-up>; your **Account ID** is on the dashboard home page (right column, "Account
  details") or in the URL after \`dash.cloudflare.com/\`. Create a token in **My Profile → API Tokens → Create Token**
  with the **Workers AI** template. Put both in your \`.env\` file, then run
  \`npm run portraits:paint -- --service cloudflare\`.
  When the daily quota is used up, the script stops; run it again the next day.

### Keys

Copy \`.env.example\` to \`.env\` at the root of the project and fill in the keys you use: the script reads it on
every run. \`.env\` is ignored by git, so the keys stay on your computer; the script never writes or prints them.
Variables set in your terminal work too (they win over \`.env\`).

## Adding a portrait by hand

- Path: \`public/images/<race>/<class>/<male|female>1.(png|webp|jpg)\`, lower case, spaces as dashes (\`dark-elf\`).
- Square image (1024 × 1024 for the existing ones), under ~2 MB; WebP is much smaller than PNG.
- Style: semi-realistic digital painting, one character from the waist up, facing the viewer, face in the upper third
  (the app crops around it), class gear clearly visible, fantasy background matching the race, no text.
- Run \`npm run portraits\` to update the list the app reads.

## Status

| Race | Class | Male | Female |
| --- | --- | --- | --- |
${rows.join('\n')}
`;
  writeFileSync(GUIDE, doc);
  return { total: portraits.length, missing: missing.length };
};
