// Lists the portraits missing for each race, class and gender, and writes docs/portraits.md (spec 009).
// Usage: node scripts/missing-portraits.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const types = readFileSync(join(root, 'src/types/character.ts'), 'utf8');

/** Values of an `as const` enum object of src/types/character.ts. */
const values = (name) => {
  const body = types.match(
    new RegExp(`export const ${name} = \\{([^}]*)\\}`),
  )[1];
  return [...body.matchAll(/:\s*'([^']+)'/g)].map((m) => m[1]);
};

const slug = (value) =>
  value
    .toLowerCase()
    .replace(/[^a-z]+/g, '-')
    .replace(/^-|-$/g, '');

const races = values('CharacterRaces');
const classes = values('CharacterClasses');
const variants = ['male', 'female']; // non-binary characters use one of both

const rows = [];
let missing = 0;
for (const race of races) {
  for (const characterClass of classes) {
    const files = variants.map((variant) => {
      const path = `public/images/${slug(race)}/${slug(characterClass)}/${variant}1.png`;
      const exists = existsSync(join(root, path));
      if (!exists) missing++;
      return exists ? '✅' : `❌ \`${path}\``;
    });
    rows.push(`| ${race} | ${characterClass} | ${files.join(' | ')} |`);
  }
}

const total = races.length * classes.length * variants.length;
const doc = `# Portraits

Generated by \`node scripts/missing-portraits.mjs\`: run it again after adding images.

**${total - missing} of ${total} portraits exist; ${missing} are missing.** Until a portrait exists, the app shows the
race emblem (a shield in the class colour with the race symbol), so nothing is broken.

## Adding a portrait

- Path: \`public/images/<race>/<class>/<male|female>1.png\`, lower case, spaces as dashes
  (\`dark-elf\`, \`half-elf\`). Non-binary characters use one of the two, chosen from their name.
- Format: PNG, 1024 × 1024 (square), under ~2 MB.
- Style of the existing portraits: semi-realistic digital painting, one character from the waist up, facing the
  viewer, face in the upper third (the app crops around it), class gear clearly visible (staff, bow, lute, shield…),
  soft fantasy background matching the race (forest, forge, underground city, ashlands…), warm light, no text.
- Race notes: halflings and gnomes are small (about half human height); half-elves have slightly pointed ears;
  dark elves have ash-grey or dusky violet skin and white hair; Ashborn have horns, ember eyes and sometimes a tail.

## Status

| Race | Class | Male | Female |
| --- | --- | --- | --- |
${rows.join('\n')}
`;

writeFileSync(join(root, 'docs/portraits.md'), doc);
console.log(
  `${missing} of ${total} portraits missing — docs/portraits.md written.`,
);
